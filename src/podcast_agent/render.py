"""Write a Report as report.json and report.md."""

from __future__ import annotations

from pathlib import Path

from .models import Report


def write(report: Report, out_dir: Path) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "report.json").write_text(report.model_dump_json(indent=2), encoding="utf-8")
    (out_dir / "report.md").write_text(markdown(report), encoding="utf-8")


def markdown(r: Report) -> str:
    guests = ", ".join(r.guests) or "none"
    lines = [
        f"# {r.title}",
        "",
        f"*Episode {r.episode_id} · Host: {r.host} · Guests: {guests}"
        + (f" · Recorded {r.recorded}" if r.recorded else "") + "*",
        "",
        "## Summary",
        "",
        r.summary,
        "",
        "## 🔹 Top takeaways",
        "",
        *[f"{i}. {t}" for i, t in enumerate(r.takeaways, 1)],
        "",
        "## 💬 Notable quotes",
        "",
        *[f"> “{q.text}”  \n> — **{q.speaker}**, `{q.ts}`\n" for q in r.quotes],
        "## 🧭 Topics",
        "",
        " ".join(f"`{t}`" for t in r.tags),
        "",
        "## Fact-check",
        "",
    ]
    if r.fact_checks:
        lines += ["| | Claim | Verification | Confidence | Said at |", "|---|---|---|---|---|"]
        for fc in r.fact_checks:
            claim = fc.claim.replace("|", "\\|")
            lines.append(f"| {fc.symbol} | {claim} | {fc.verification.replace('|', '/')} | {fc.confidence:.2f} | "
                         f"{fc.speaker} `{fc.ts}` |")
        lines += ["", "<details><summary>Fact-check reasoning</summary>", ""]
        for fc in r.fact_checks:
            samples = f" · samples: {', '.join(fc.labels)}" if fc.labels else ""
            queries = f" · searches: {'; '.join(fc.queries)}" if fc.queries else ""
            lines.append(f"- {fc.symbol} **{fc.claim}** ({fc.type}, {fc.method}{samples}{queries}): {fc.reasoning}")
        lines += ["", "</details>"]
    else:
        lines.append("No checkable factual claims found.")
    lines += ["", "---", f"*Generated by podcast-agent · harness `{r.harness_version}` · model `{r.model}`"]
    if r.degraded:
        lines.append(f" · ⚠ degraded: {'; '.join(r.degraded)}")
    lines[-1] += "*"
    return "\n".join(lines) + "\n"
